-- V15: Employee ↔ Store assignment (many-to-many).
-- An employee can be assigned to many stores and a store can carry many
-- assigned employees, but every assignment row ties an employee and a
-- store that share the same owning Organization. Roles, permissions,
-- scheduling, and shift management are intentionally not part of this
-- layer.
-- employee_store_assignment:
--   * uk_employee_store_assignment on (employee_id, store_id) is the
--     database-level duplicate prevention for a pair; the service layer
--     also refuses to re-add an existing assignment so PUT is idempotent.
--   * organization_id is denormalized onto the row so two composite foreign
--     keys can pin both sides to a single organization at the database
--     level: fk_esa_employee on (employee_id, organization_id) referencing
--     employee (id, organization_id) and fk_esa_store on
--     (store_id, organization_id) referencing stores (id, organization_id).
--     Together they make a cross-organization assignment impossible to
--     write even if the service check is bypassed, and they also block
--     moving an employee or a store to another organization while the other
--     side still has assignments.
--   * uk_stores_id_organization is added on stores to support the composite
--     store FK (employee already carries the matching
--     uk_employee_id_organization from V14).
--   * The (employee_id, store_id) unique index already covers the
--     "list an employee's stores" lookup through its leading column, so an
--     explicit index is only needed for the "list a store's employees"
--     direction on store_id.
-- Deleting an employee or a store that still carries assignments is
-- rejected by the foreign keys and pre-empted by the service-layer delete
-- guards, so no assignment row can dangle.

ALTER TABLE stores ADD CONSTRAINT uk_stores_id_organization UNIQUE (id, organization_id);

CREATE TABLE employee_store_assignment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    employee_id     BIGINT NOT NULL,
    store_id        BIGINT NOT NULL,
    CONSTRAINT uk_employee_store_assignment UNIQUE (employee_id, store_id),
    CONSTRAINT fk_esa_employee FOREIGN KEY (employee_id, organization_id) REFERENCES employee (id, organization_id),
    CONSTRAINT fk_esa_store FOREIGN KEY (store_id, organization_id) REFERENCES stores (id, organization_id)
);

CREATE INDEX idx_esa_store_id ON employee_store_assignment (store_id);
