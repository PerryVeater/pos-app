-- V16: Employee POS PIN credentials with store-scoped uniqueness.
-- An employee may hold at most one POS PIN within their organization. The
-- PIN is a short numeric secret, so it is never stored in plaintext:
-- employee_pin_credential holds a salted password hash (pin_hash) used for
-- verification, plus a deterministic HMAC fingerprint (pin_fingerprint)
-- used ONLY to detect two employees trying to share the same PIN at the
-- same store. The fingerprint is a keyed hash and is treated as sensitive;
-- it is never returned by the API.
-- employee_pin_credential:
--   * uk_employee_pin_credential_employee enforces one credential per
--     employee (the PIN is set or replaced through an upsert keyed on the
--     employee).
--   * fk_epc_employee is ON DELETE CASCADE so an employee without store
--     assignments can still be deleted while carrying a credential; the
--     credential is subordinate data, not an aggregate.
--   * idx_epc_pin_fingerprint supports reverse fingerprint lookups.
-- employee_pin_store_scope (the store-scoped uniqueness enforcement table):
--   * One row per (assigned store) for each employee that currently holds a
--     PIN, carrying that employee's fingerprint. This is the database-level
--     materialization of the rule "two employees assigned to a common store
--     must not share a PIN"; it is derived from, and never replaces, the
--     employee_store_assignment relationship.
--   * uk_epss_store_fingerprint on (store_id, pin_fingerprint) is the core
--     guarantee: within a single store no two employees may claim the same
--     PIN fingerprint. It is the concurrency backstop for both the PIN
--     set/change flow and the assignment flow.
--   * uk_epss_employee_store on (employee_id, store_id) keeps exactly one
--     claim row per employee-store, which also makes the insert idempotent
--     for a repeated PUT of the same assignment.
--   * fk_epss_assignment on (employee_id, store_id) references
--     employee_store_assignment (employee_id, store_id) ON DELETE CASCADE,
--     so removing an assignment automatically releases that employee's PIN
--     claim at the store. fk_epss_employee and fk_epss_store are also
--     ON DELETE CASCADE for the same reason.
--   * An employee assigned to several stores repeats their single
--     fingerprint on one row per store (different store_id), so the same
--     PIN is valid at every assigned store while remaining unique per
--     store. Employees with no PIN create no scope rows and are unaffected.

CREATE TABLE employee_pin_credential (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     BIGINT       NOT NULL,
    pin_hash        VARCHAR(255) NOT NULL,
    pin_fingerprint VARCHAR(128) NOT NULL,
    CONSTRAINT uk_employee_pin_credential_employee UNIQUE (employee_id),
    CONSTRAINT fk_epc_employee FOREIGN KEY (employee_id) REFERENCES employee (id) ON DELETE CASCADE
);

CREATE INDEX idx_epc_pin_fingerprint ON employee_pin_credential (pin_fingerprint);

CREATE TABLE employee_pin_store_scope (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     BIGINT       NOT NULL,
    store_id        BIGINT       NOT NULL,
    pin_fingerprint VARCHAR(128) NOT NULL,
    CONSTRAINT uk_epss_store_fingerprint UNIQUE (store_id, pin_fingerprint),
    CONSTRAINT uk_epss_employee_store UNIQUE (employee_id, store_id),
    CONSTRAINT fk_epss_employee FOREIGN KEY (employee_id) REFERENCES employee (id) ON DELETE CASCADE,
    CONSTRAINT fk_epss_store FOREIGN KEY (store_id) REFERENCES stores (id) ON DELETE CASCADE,
    CONSTRAINT fk_epss_assignment FOREIGN KEY (employee_id, store_id) REFERENCES employee_store_assignment (employee_id, store_id) ON DELETE CASCADE
);
