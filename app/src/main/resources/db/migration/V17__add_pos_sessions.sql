-- V17: POS authentication sessions.
-- pos_session: a temporary, store-scoped bearer session issued when an
-- employee authenticates at a specific store with their PIN. The raw token
-- is returned to the client exactly once and never persisted; only a
-- cryptographic hash of it (a SHA-256 hex digest) is stored, because the
-- token itself is a high-entropy random value so a fast hash is enough for
-- equality lookup and offers no offline-guessing surface.
--   * token_hash is NOT NULL and unique through uk_pos_session_token_hash,
--     which is both the authentication lookup key and the integrity guard
--     against a (astronomically unlikely) hash collision issuing two live
--     sessions the same token.
--   * employee_id and store_id pin the session to the authenticated
--     employee and the store it was opened at; a session is meaningless
--     outside that pair. Both are ON DELETE CASCADE so sessions are
--     ephemeral subordinate data that never blocks employee or store
--     removal (unlike assignments, which are guarded at the service layer).
--   * created_at records issuance, expires_at the configured lifetime
--     boundary, and revoked_at is the revocation marker: NULL means the
--     session is still live, a timestamp means it has been logged out. A
--     session is usable only while revoked_at IS NULL and the current time
--     precedes expires_at.
-- Timestamps are stored as UTC ("timestamp with time zone") to match the
-- java.time.Instant fields on the entity, following the requirement that
-- session lifetimes be absolute and zone-independent.
-- Explicit indexes cover the token hash lookup and the employee/store
-- foreign-key columns.

CREATE TABLE pos_session (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  VARCHAR(64)           NOT NULL,
    employee_id BIGINT                NOT NULL,
    store_id    BIGINT                NOT NULL,
    created_at  TIMESTAMPTZ           NOT NULL,
    expires_at  TIMESTAMPTZ           NOT NULL,
    revoked_at  TIMESTAMPTZ,
    CONSTRAINT uk_pos_session_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_pos_session_employee FOREIGN KEY (employee_id) REFERENCES employee(id) ON DELETE CASCADE,
    CONSTRAINT fk_pos_session_store FOREIGN KEY (store_id) REFERENCES stores(id) ON DELETE CASCADE
);

CREATE INDEX idx_pos_session_employee_id ON pos_session (employee_id);
CREATE INDEX idx_pos_session_store_id ON pos_session (store_id);
